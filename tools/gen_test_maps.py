    m.add(box((-W - 16, -W - 16, -16), (W + 16, W + 16, 0), floor))
    m.add(box((-W - 16, -W - 16, H), (W + 16, W + 16, H + 16), sky))
    m.add(box((-W - 16, -W, 0), (-W, W, H), wall))           # west
