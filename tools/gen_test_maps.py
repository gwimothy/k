#!/usr/bin/env python3
"""Writes the test maps in base/maps/src/ as TrenchBroom-compatible Valve 220 .map files.

    python3 tools/gen_test_maps.py

The maps are plain text: open them in TrenchBroom (see tools/trenchbroom/) to edit visually.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "base", "maps", "src")


def sub(a, b): return (a[0] - b[0], a[1] - b[1], a[2] - b[2])
def add(a, b): return (a[0] + b[0], a[1] + b[1], a[2] + b[2])
def mul(a, s): return (a[0] * s, a[1] * s, a[2] * s)
def dot(a, b): return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]
def cross(a, b): return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def norm(a):
    l = dot(a, a) ** 0.5
    return (a[0] / l, a[1] / l, a[2] / l)


def tex_axes(n):
    """World-aligned Valve 220 axes, matching the engine's planar mapping."""
    ax, ay, az = abs(n[0]), abs(n[1]), abs(n[2])
    if az >= ax and az >= ay:
        return (1, 0, 0), (0, -1, 0)
    if ax >= ay:
        return (0, 1, 0), (0, 0, -1)
    return (1, 0, 0), (0, 0, -1)


def fmt(v):
    return "( " + " ".join("%g" % round(c, 6) for c in v) + " )"


class Brush:
    def __init__(self):
        self.faces = []  # (normal, point, texture)

    def plane(self, normal, point, texture):
        self.faces.append((norm(normal), point, texture))
        return self

    def text(self):
        out = ["{"]
        for n, p, tex in self.faces:
            # Three points with (p0 - p1) x (p2 - p1) pointing along n (Quake convention).
            u = (1, 0, 0) if abs(n[0]) < 0.9 else (0, 0, 1)
            u = norm(sub(u, mul(n, dot(u, n))))
            v = cross(n, u)
            p1 = p
            p0 = add(p, mul(u, 64))
            p2 = add(p, mul(v, 64))
            ua, va = tex_axes(n)
            out.append("%s %s %s %s [ %g %g %g 0 ] [ %g %g %g 0 ] 0 1 1" % (
                fmt(p0), fmt(p1), fmt(p2), tex, *ua, *va))
        out.append("}")
        return "\n".join(out)


def box(mins, maxs, tex):
    """tex: a string, or a dict with keys top/bottom/north/south/east/west and a default."""
    def t(face):
        return tex if isinstance(tex, str) else tex.get(face, tex.get("default"))
    b = Brush()
    b.plane((0, 0, 1), maxs, t("top"))
    b.plane((0, 0, -1), mins, t("bottom"))
    b.plane((1, 0, 0), maxs, t("east"))
    b.plane((-1, 0, 0), mins, t("west"))
    b.plane((0, 1, 0), maxs, t("north"))
    b.plane((0, -1, 0), mins, t("south"))
    return b


def ramp_x(mins, maxs, tex):
    """Wedge rising along +X from mins.x (height 0) to maxs.x (full height)."""
    x0, y0, z0 = mins
    x1, y1, z1 = maxs
    b = Brush()
    b.plane((0, 0, -1), mins, tex)
    b.plane((1, 0, 0), maxs, tex)
    b.plane((0, -1, 0), mins, tex)
    b.plane((0, 1, 0), maxs, tex)
    b.plane((-(z1 - z0), 0, x1 - x0), (x0, y0, z0), tex)
    return b


class Map:
    def __init__(self, worldspawn):
        self.world = worldspawn
        self.brushes = []
        self.entities = []  # (keys, brushes)

    def add(self, *brushes):
        self.brushes.extend(brushes)

    def entity(self, keys, brushes=()):
        self.entities.append((keys, list(brushes)))

    def write(self, name):
        os.makedirs(ROOT, exist_ok=True)
        out = ["// Generated by tools/gen_test_maps.py - safe to edit in TrenchBroom", "{"]
        out += ['"%s" "%s"' % kv for kv in self.world.items()]
        out += [b.text() for b in self.brushes]
        out.append("}")
        for keys, brushes in self.entities:
            out.append("{")
            out += ['"%s" "%s"' % kv for kv in keys.items()]
            out += [b.text() for b in brushes]
            out.append("}")
        path = os.path.join(ROOT, name + ".map")
        with open(path, "w") as f:
            f.write("\n".join(out) + "\n")
        print("wrote", os.path.normpath(path))


def hollow_room(m, mins, maxs, wall, floor, ceiling, t=16, skip=()):
    """Six slabs around an interior volume. `skip` names walls to leave out."""
    (x0, y0, z0), (x1, y1, z1) = mins, maxs
    slabs = {
        "floor": ((x0 - t, y0 - t, z0 - t), (x1 + t, y1 + t, z0), floor),
        "ceiling": ((x0 - t, y0 - t, z1), (x1 + t, y1 + t, z1 + t), ceiling),
        "west": ((x0 - t, y0, z0), (x0, y1, z1), wall),
        "east": ((x1, y0, z0), (x1 + t, y1, z1), wall),
        "south": ((x0 - t, y0 - t, z0), (x1 + t, y0, z1), wall),
        "north": ((x0 - t, y1, z0), (x1 + t, y1 + t, z1), wall),
    }
    for name, (lo, hi, tex) in slabs.items():
        if name not in skip:
            m.add(box(lo, hi, tex))


