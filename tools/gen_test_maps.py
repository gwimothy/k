    m.add(box((cx0, -80, 0), (cx1, -64, 128), wall))
    m.add(box((cx0, 64, 0), (cx1, 80, 128), wall))
    rx0, rx1, ry0, ry1, rh = cx1, cx1 + 512, -256, 256, 192
    hollow_room(m, (rx0, ry0, 0), (rx1, ry1, rh), wall, floor, "dev/dev_ceiling", skip=("west",))
    m.add(box((rx0 - 16, ry0, 0), (rx0, -64, rh), wall))
    m.add(box((rx0 - 16, 64, 0), (rx0, ry1, rh), wall))
    m.add(box((rx0 - 16, -64, 128), (rx0, 64, rh), wall))
    m.add(box((rx0 + 192, -64, 0), (rx0 + 320, 64, 96), "dev/dev_orange"))  # table in the dark room

    # Hall contents: crate block, stairs, ramp, pillars.
