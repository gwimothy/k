    m.add(box((-W - 16, W, 0), (W + 16, W + 16, H), wall))    # north
    # East wall in three pieces around a 128x128 doorway at y in [-64, 64].
    m.add(box((W, -W, 0), (W + 16, -64, H), wall))
    m.add(box((W, 64, 0), (W + 16, W, H), wall))
    m.add(box((W, -64, 128), (W + 16, 64, H), wall))

    # Corridor (east), 512 long, then a dark room lit by a lamp.
    cx0, cx1 = W + 16, W + 528
    m.add(box((cx0, -80, -16), (cx1, 80, 0), floor))           # floor
